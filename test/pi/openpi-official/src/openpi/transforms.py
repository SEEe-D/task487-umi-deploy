def _rot6d_to_matrix(rot6d: np.ndarray) -> np.ndarray:
    """rot6d (6,) -> rotation matrix (3,3) via Gram-Schmidt."""
    r1 = rot6d[:3].copy()
    r2 = rot6d[3:6].copy()
    r1 = r1 / (np.linalg.norm(r1) + 1e-8)
    r2 = r2 - np.dot(r2, r1) * r1
    r2 = r2 / (np.linalg.norm(r2) + 1e-8)
    r3 = np.cross(r1, r2)
    return np.stack([r1, r2, r3], axis=1)


def _matrix_to_rot6d(R: np.ndarray) -> np.ndarray:
    """rotation matrix (3,3) -> rot6d (6,)."""
    return R[:, :2].T.flatten()


class GlobalToBodyDelta(DataTransformFn):
    """Converts absolute EE poses to body-frame deltas (proper SE(3)).

    Input:  actions 是绝对位姿 (和 state 同坐标系)
    Output: actions 是末端局部坐标系 delta

    Position: body_delta = R_current^T @ (action_pos - state_pos)
    Rotation: R_body_delta = R_current^T @ R_target (几何相对旋转, 不是 rot6d 减法)

    等价于 UMI 的 inv(T_current) @ T_target。
    Must run BEFORE RelativeState. 不需要 DeltaActions。
    """

    def __call__(self, data: DataDict) -> DataDict:
        if "actions" not in data:
            return data

        state = data["state"]
        actions = np.array(data["actions"], copy=True)
        R_current = _rot6d_to_matrix(state[3:9])

        for i in range(len(actions)):
            # Position: 绝对位姿差 → 末端局部坐标系
            delta_pos = actions[i, :3] - state[:3]
            actions[i, :3] = R_current.T @ delta_pos

            # Rotation: 绝对旋转 → SE(3) 几何相对旋转
            R_target = _rot6d_to_matrix(actions[i, 3:9])
            R_relative = R_current.T @ R_target
            actions[i, 3:9] = _matrix_to_rot6d(R_relative)

        data["actions"] = actions
        return data


class BodyToGlobalDelta(DataTransformFn):
    """Inverse of GlobalToBodyDelta: body-frame deltas → absolute EE poses.

    Position: target_pos = state_pos + R_current @ body_delta_pos
    Rotation: R_target = R_current @ R_body_delta → absolute rot6d

    At inference with state=identity: output = body_delta (identity 乘法无影响).
    Deploy 脚本直接 rot6d_to_matrix(action[3:9]) 即可, 不需要额外处理。
    """

    def __call__(self, data: DataDict) -> DataDict:
        if "actions" not in data:
            return data

        state = data["state"]
        actions = np.array(data["actions"], copy=True)
        R_current = _rot6d_to_matrix(state[3:9])

        for i in range(len(actions)):
            # Position: 末端局部 → 绝对位姿
            actions[i, :3] = state[:3] + R_current @ actions[i, :3]

            # Rotation: body relative → absolute rot6d
            R_relative = _rot6d_to_matrix(actions[i, 3:9])
            R_target = R_current @ R_relative
            actions[i, 3:9] = _matrix_to_rot6d(R_target)

        data["actions"] = actions
        return data


@dataclasses.dataclass(frozen=True)
class RelativeState(DataTransformFn):
    """Converts state to current-frame-relative (like UMI obs_pose_repr=relative).

    For single-frame obs (Pi0.5), relative to current frame = identity:
    - Position: [0, 0, 0]
    - Rotation (rot6d): [1, 0, 0, 0, 1, 0] (identity matrix columns)
    - Gripper: preserved (absolute value)

    Masked dimensions are zeroed (pose), unmasked dimensions are preserved (gripper).
    This makes state coordinate-system-independent: no SLAM/robot frame matching needed.
    """

    mask: Sequence[bool] | None

    def __call__(self, data: DataDict) -> DataDict:
        if self.mask is None:
            return data

        state = np.array(data["state"], copy=True)
        mask = np.asarray(self.mask)
        dims = mask.shape[-1]

        # Zero out masked dimensions (pose), keep unmasked (gripper)
        identity_state = np.zeros_like(state[..., :dims])
        # rot6d identity: columns of I = [1,0,0, 0,1,0] at indices 3:9 (and 13:19 for left arm)
        # For the mask pattern [T]*9 + [F] + [T]*9 + [F]:
        # Right arm rot6d at 3:9, left arm rot6d at 13:19
        for arm_offset in [0, 10]:
            rot_start = arm_offset + 3
            rot_end = arm_offset + 9
            if rot_end <= dims:
                identity_state[..., rot_start:rot_end] = [1, 0, 0, 0, 1, 0]

        state[..., :dims] = np.where(mask, identity_state[..., :dims], state[..., :dims])
        data["state"] = state

        return data


@dataclasses.dataclass(frozen=True)
class DeltaActions(DataTransformFn):
    """Repacks absolute actions into delta action space."""

    # Boolean mask for the action dimensions to be repacked into delta action space. Length
    # can be smaller than the actual number of dimensions. If None, this transform is a no-op.
    # See `make_bool_mask` for more details.
    mask: Sequence[bool] | None

    def __call__(self, data: DataDict) -> DataDict:
        if "actions" not in data or self.mask is None:
            return data

        state, actions = data["state"], data["actions"]
        mask = np.asarray(self.mask)
        dims = mask.shape[-1]
        actions[..., :dims] -= np.expand_dims(np.where(mask, state[..., :dims], 0), axis=-2)
        data["actions"] = actions

        return data


